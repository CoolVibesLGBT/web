import assert from 'node:assert/strict'
import { browser, setup } from './fixture.mjs'
try {
 for (const item of [{width:320,language:'tr',theme:'light'},{width:390,language:'en',theme:'dark'},{width:820,language:'ar',theme:'light',large:true},{width:1440,language:'en',theme:'light'}]) {
  const {page,context,errors}=await setup(item)
  await page.emulateMedia({reducedMotion:'no-preference'})
  await page.goto('http://localhost:5173/settings/appearance')
  const mainToggle=page.getByRole('switch').first()
  await mainToggle.click()
  assert.equal(await mainToggle.getAttribute('aria-checked'),'false')
  await page.reload()
  assert.equal(await mainToggle.getAttribute('aria-checked'),'false')
  await mainToggle.click()
  await page.goto('http://localhost:5173/settings/appearance/background')
  const canvas=page.locator('.cv-appearance-preview canvas')
  const toggle=page.getByRole('switch').first()
  const pixels=()=>canvas.evaluate(el=>Array.from(el.getContext('2d').getImageData(0,0,50,50).data).join(','))
  await page.locator('.cv-appearance-preview canvas[data-motion="running"]').waitFor()
  const before=await pixels();await page.waitForTimeout(800);assert.notEqual(await pixels(),before)
  await toggle.click()
  await page.locator('.cv-appearance-preview canvas[data-motion="paused"]').waitFor()
  const paused=await pixels();await page.waitForTimeout(200);assert.equal(await pixels(),paused)
  await page.reload()
  await page.locator('.cv-appearance-preview canvas[data-motion="paused"]').waitFor()
  assert.equal(await toggle.getAttribute('aria-checked'),'false')
  await toggle.click()
  await page.locator('.cv-appearance-preview canvas[data-motion="running"]').waitFor()
  await page.emulateMedia({reducedMotion:'reduce'})
  await page.locator('.cv-appearance-preview canvas[data-motion="paused"]').waitFor()
  const reduced=await pixels();await page.waitForTimeout(200);assert.equal(await pixels(),reduced)
  await page.emulateMedia({reducedMotion:'no-preference'})
  await page.goto('http://localhost:5173/messages')
  await page.locator('.cv-chat-row-main').filter({hasText:'Theme Friend'}).click()
  await page.locator('.cv-chat-thread .cv-chat-wallpaper canvas[data-motion="running"]').waitFor()
  assert.deepEqual(errors,[])
  await context.close()
 }
 console.log('Gradient animation: pixels move, toggle persists, reduced motion pauses, chat animates; four viewport/locale fixtures passed.')
} finally {await browser.close()}
